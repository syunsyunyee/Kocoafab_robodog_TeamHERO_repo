import json
import unittest
import test_curriculum as curriculum_tests
from web_kiosk import KioskModel
from test_web import FakeWorker

class ModeTests(unittest.TestCase):
    setUp = curriculum_tests.CurriculumTests.setUp
    tearDown = curriculum_tests.CurriculumTests.tearDown
    act = curriculum_tests.CurriculumTests.act
    full_order = curriculum_tests.CurriculumTests.full_order

    def test_guided_blocks_wrong_choice_and_praises_correct_choice(self):
        self.act("start_stage", "1")
        self.act("service", "매장에서 먹기")
        with self.assertRaises(ValueError):
            self.act("next")
        snapshot = self.act("service", "가져가기")
        self.assertTrue(snapshot["ui"]["assisted"])
        self.assertIn("PRAISE", self.worker.actions)
        self.act("next")
        self.assertEqual(self.model.session.screen, "menu")
        self.assertFalse(self.model.completed_stages)

    def test_practice_allows_wrong_order_reviews_all_options_and_can_correct(self):
        self.act("set_mode", "practice")
        self.act("start_stage", "15")
        self.act("service", "가져가기")
        self.act("next")
        self.act("menu", "americano")
        self.act("next")
        response = self.act("temperature", "차갑게")
        self.assertFalse(response["ui"]["assisted"])
        self.assertFalse(response["ui"]["autoSpeak"])
        self.assertNotIn("PRAISE", self.worker.actions)
        self.act("next")
        response = self.act("complete")
        wrong = {item["field"] for item in response["review"]["items"] if not item["correct"]}
        self.assertEqual(wrong, {"size", "shot", "whipped", "chocochip", "sweetness", "side"})
        self.assertNotIn("SUCCESS", self.worker.actions)
        self.assertFalse(self.model.completed_stages)
        self.act("resume_review")
        self.act("edit_options")
        for key in wrong:
            self.act(key, self.model.target[key])
        self.act("next")
        self.act("complete")
        self.assertEqual(self.model.completed_stages, {15})
        self.assertEqual(self.worker.actions.count("SUCCESS"), 1)
        rows = [json.loads(line) for line in (self.base / "data/results.jsonl").read_text().splitlines()]
        self.assertEqual([row["correct"] for row in rows], [False, True])

    def test_help_only_reveals_current_screen(self):
        self.act("set_mode", "practice")
        self.act("start_stage", "2")
        self.act("service", "가져가기")
        self.act("next")
        response = self.act("help")
        self.assertTrue(response["ui"]["assisted"])
        self.assertIn("음료", response["message"])
        self.assertEqual(response["helpCount"], 1)
        self.act("repeat")
        self.assertEqual(self.model.session.help_count, 1)
        self.act("menu", "strawberry_latte")
        response = self.act("next")
        self.assertFalse(response["ui"]["assisted"])
        self.assertEqual(response["mode"], "practice")

    def test_guided_rewards_once_per_satisfied_screen_not_each_option_or_navigation(self):
        self.act("start_stage", "15")
        target = self.model.target
        for field in ("service", "menu"):
            self.act(field, target[field])
            before = self.worker.actions.count("PRAISE")
            self.act(field, target[field])
            self.act("next")
            self.assertEqual(self.worker.actions.count("PRAISE"), before)
        self.assertEqual(self.worker.actions.count("PRAISE"), 2)
        self.act("temperature", target["temperature"])
        for field in ("size", "shot", "whipped", "chocochip", "sweetness"):
            self.act(field, target[field])
            self.assertEqual(self.worker.actions.count("PRAISE"), 2)
        self.act("side", target["side"])
        self.assertEqual(self.worker.actions.count("PRAISE"), 3)
        self.act("side", target["side"])
        self.act("next")
        self.act("edit_options")
        self.act("side", "없음")
        self.act("side", target["side"])
        self.act("next")
        self.act("complete")
        self.act("complete")
        self.assertEqual(self.worker.actions.count("PRAISE"), 3)
        self.assertNotIn("SUCCESS", self.worker.actions)
        self.assertEqual(self.worker.actions.count("COMPLETE"), 1)

    def test_separate_progress_and_previous_curriculum_is_preserved(self):
        self.act("start_stage", "1")
        self.full_order()
        self.act("home")
        self.act("set_mode", "practice")
        self.assertFalse(self.model.completed_stages)
        self.act("start_stage", "1")
        self.full_order()
        loaded = KioskModel(FakeWorker(), self.base)
        self.assertEqual(loaded.completed_by_mode, {"guided": {1}, "practice": {1}})
        old = {"completedByMode": {"guided": [1, 2, 3, 4, 5, 6], "practice": [1]}}
        (self.base / "data/progress.json").write_text(json.dumps(old))
        loaded = KioskModel(FakeWorker(), self.base)
        self.assertEqual(loaded.completed_by_mode, {"guided": set(), "practice": set()})
        self.assertEqual(loaded.legacy_progress, old)
        loaded._save_progress()
        saved = json.loads((self.base / "data/progress.json").read_text())
        self.assertEqual(saved["previousCurriculum"], old)

    def test_guidance_only_mentions_current_screen_then_reads_full_confirmation(self):
        s = self.act("start_stage", "15")
        for text in (s["message"], s["screenTask"]):
            for future in ("아메리카노", "샷", "벤티", "머핀"):
                self.assertNotIn(future, text)
        self.assertIn("가져가기", s["screenTask"])
        self.act("service", "가져가기")
        s = self.act("next")
        self.assertIn("음료", s["message"])
        self.assertIn("아메리카노", s["screenTask"])
        self.assertNotIn("샷", s["message"])
        self.assertNotIn("벤티", s["screenTask"])
        self.act("menu", "americano")
        s = self.act("next")
        self.assertIn("온도", s["message"])
        self.assertNotIn("샷", s["message"])
        self.act("temperature", "차갑게")
        self.assertIn("크기", self.model.message)
        for key in ("size", "shot", "whipped", "chocochip", "sweetness", "side"):
            self.act(key, self.model.target[key])
        s = self.act("next")
        for detail in ("아메리카노", "벤티", "샷 2번 추가", "초코 머핀"):
            self.assertIn(detail, s["message"])
        s = self.act("back")
        self.assertNotIn("아메리카노", s["message"])

    def test_random_start_and_requested_help_stay_on_current_screen(self):
        self.act("set_mode", "practice")
        s = self.act("start_stage", "16")
        for future in ("샷", "크기", "휘핑", "사이드"):
            self.assertNotIn(future, s["message"])
        s = self.act("help")
        self.assertIn(self.model.target["service"], s["message"])
        self.assertNotIn("샷", s["message"])
        self.assertEqual(self.act("repeat")["message"], s["message"])

    def test_basic_hint_and_detailed_help_have_distinct_scope_and_stay_at_requested_level(self):
        basic = self.act("start_stage", "15")
        hint = self.act("hint")
        detailed = self.act("help")
        self.assertEqual([s["ui"]["assistanceLevel"] for s in (basic, hint, detailed)], [1, 2, 3])
        self.assertEqual(len({s["message"] for s in (basic, hint, detailed)}), 3)
        self.assertIn("봉투", hint["message"])
        self.assertNotIn("‘가져가기’", hint["message"])
        self.assertIn("‘가져가기’", detailed["message"])
        self.assertIn("1.", detailed["message"])
        for _ in range(3):
            s = self.act("hint")
            self.assertEqual(s["ui"]["assistanceLevel"], 2)
        self.assertEqual(self.act("repeat")["message"], s["message"])
        self.assertEqual(self.model.session.help_count, 5)
        self.assertNotIn("PRAISE", self.worker.actions)
        self.act("service", "가져가기")
        menu = self.act("next")
        self.assertEqual(menu["ui"]["assistanceLevel"], 1)
        self.assertNotIn("아메리카노", menu["message"])
        hint = self.act("hint")
        self.assertIn("커피", hint["message"])
        self.assertNotIn("아메리카노", hint["message"])
        detailed = self.act("help")
        self.assertIn("아메리카노", detailed["message"])

    def test_option_hint_explains_concept_detailed_help_names_exact_choice(self):
        self.act("start_stage", "15")
        self.act("service", "가져가기")
        self.act("next")
        self.act("menu", "americano")
        basic = self.act("next")
